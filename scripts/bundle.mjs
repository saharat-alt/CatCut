// Single-file build for installs without npm: dist/bundle/catcut.mjs + a trimmed pdfjs-dist next to it.
// Two folders deep on purpose: ../../jsx and ../../web resolve exactly as from dist/<dir>/*.js.
import { build } from 'esbuild';
import { cp, mkdir, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'dist', 'bundle');
const require = createRequire(import.meta.url);

await rm(out, { recursive: true, force: true });
await build({
  entryPoints: [join(root, 'src', 'mcp', 'cli.ts')],
  outfile: join(out, 'catcut.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  external: ['pdfjs-dist', 'pdfjs-dist/*'],
  define: { 'process.env.CATCUT_BUNDLED': '"1"' },
  // CommonJS dependencies call require() for Node built-ins.
  banner: { js: "import { createRequire as __catcutRequire } from 'node:module'; const require = __catcutRequire(import.meta.url);" },
  legalComments: 'none',
  logLevel: 'warning',
});

// pdfjs loads its worker, CMaps and standard fonts from its own folder: ship only those files.
const pdfRoot = dirname(require.resolve('pdfjs-dist/package.json'));
const pdfOut = join(out, 'node_modules', 'pdfjs-dist');
await mkdir(join(pdfOut, 'legacy', 'build'), { recursive: true });
for (const f of ['package.json', 'LICENSE', 'legacy/build/pdf.mjs', 'legacy/build/pdf.worker.mjs']) await cp(join(pdfRoot, f), join(pdfOut, f));
for (const d of ['cmaps', 'standard_fonts']) await cp(join(pdfRoot, d), join(pdfOut, d), { recursive: true });
await writeFile(join(out, 'README.txt'), 'Generated by scripts/bundle.mjs (npm run build). Do not edit.\n');
console.log(`bundle: ${join(out, 'catcut.mjs')}`);
